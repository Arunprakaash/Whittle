"""Imports the Material Symbols Rounded icons listed in icons.txt as Android vector drawables.

Writes res/drawable/ms_<name>.xml (and ms_<name>_fill.xml for ":fill" entries) plus MaterialSymbols.kt,
which maps each symbol name to its drawable so config can name icons ("language", "schedule") safely.
Material Symbols are Apache 2.0 licensed: https://github.com/google/material-design-icons

Usage: python3 design/system/icons/import_material_symbols.py
"""

import re
import urllib.request
from pathlib import Path

MODULE_DIR = Path(__file__).resolve().parent.parent
ICON_LIST = MODULE_DIR / "icons" / "icons.txt"
DRAWABLE_DIR = MODULE_DIR / "src" / "main" / "res" / "drawable"
KOTLIN_FILE = MODULE_DIR / "src" / "main" / "kotlin" / "app" / "whittle" / "design" / "icons" / "MaterialSymbols.kt"
SOURCE_URL = "https://fonts.gstatic.com/s/i/short-term/release/materialsymbolsrounded/{name}/{style}/24px.svg"
DRAWABLE_PREFIX = "ms_"
FILL_SUFFIX = "_fill"
VIEWBOX = re.compile(r'viewBox="0 -960 960 960"')
PATH = re.compile(r'<path d="([^"]+)"\s*/>')
NAME = re.compile(r"^[a-z0-9_]+$")


def read_icon_list() -> list[tuple[str, bool]]:
    icons = []
    for line in ICON_LIST.read_text(encoding="utf-8").splitlines():
        line = line.strip()
        if not line or line.startswith("#"):
            continue
        name, _, variant = line.partition(":")
        if not NAME.match(name) or variant not in ("", "fill"):
            raise SystemExit(f"Bad entry in {ICON_LIST.name}: {line!r}")
        icons.append((name, variant == "fill"))
    return icons


def fetch_path(name: str, style: str) -> str:
    with urllib.request.urlopen(SOURCE_URL.format(name=name, style=style), timeout=30) as response:
        svg = response.read().decode("utf-8")
    paths = PATH.findall(svg)
    if not VIEWBOX.search(svg) or len(paths) != 1:
        raise SystemExit(f"Unexpected SVG shape for {name} ({style})")
    return paths[0]


def vector_drawable(path_data: str) -> str:
    # Symbols use a 960-unit viewBox shifted up by 960; translate it back into the viewport.
    return f"""<?xml version="1.0" encoding="utf-8"?>
<!-- Material Symbols Rounded (Apache 2.0). Generated by icons/import_material_symbols.py. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="24dp"
    android:height="24dp"
    android:viewportWidth="960"
    android:viewportHeight="960">
    <group android:translateY="960">
        <path
            android:fillColor="#FF000000"
            android:pathData="{path_data}" />
    </group>
</vector>
"""


def kotlin_map(icons: list[tuple[str, bool]]) -> str:
    outlined = "\n".join(f'        "{name}" to R.drawable.{DRAWABLE_PREFIX}{name},' for name, _ in icons)
    filled = "\n".join(
        f'        "{name}" to R.drawable.{DRAWABLE_PREFIX}{name}{FILL_SUFFIX},' for name, fill in icons if fill
    )
    return f"""// Generated by design/system/icons/import_material_symbols.py from icons.txt. Do not edit.
package app.whittle.design.icons

import androidx.annotation.DrawableRes
import app.whittle.design.R

/** Bundled Material Symbols Rounded, by symbol name. Config refers to icons by these names. */
object MaterialSymbols {{
    private val outlined: Map<String, Int> = mapOf(
{outlined}
    )

    private val filled: Map<String, Int> = mapOf(
{filled}
    )

    val names: Set<String> get() = outlined.keys

    /** The filled variant when one is bundled and [fill] is set; otherwise the outlined one. */
    @DrawableRes
    fun drawable(name: String, fill: Boolean = false): Int? = (if (fill) filled[name] else null) ?: outlined[name]
}}
"""


def main() -> None:
    icons = read_icon_list()
    DRAWABLE_DIR.mkdir(parents=True, exist_ok=True)
    for stale in DRAWABLE_DIR.glob(f"{DRAWABLE_PREFIX}*.xml"):
        stale.unlink()
    for name, fill in icons:
        (DRAWABLE_DIR / f"{DRAWABLE_PREFIX}{name}.xml").write_text(vector_drawable(fetch_path(name, "default")), encoding="utf-8")
        if fill:
            (DRAWABLE_DIR / f"{DRAWABLE_PREFIX}{name}{FILL_SUFFIX}.xml").write_text(
                vector_drawable(fetch_path(name, "fill1")), encoding="utf-8"
            )
    KOTLIN_FILE.parent.mkdir(parents=True, exist_ok=True)
    KOTLIN_FILE.write_text(kotlin_map(icons), encoding="utf-8")
    print(f"Imported {len(icons)} icons into {DRAWABLE_DIR.relative_to(MODULE_DIR)}")


if __name__ == "__main__":
    main()
