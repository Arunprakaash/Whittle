package app.whittle.tools.api

import app.whittle.core.model.Provenance
import kotlinx.serialization.Serializable
import kotlinx.serialization.json.JsonObject

@Serializable
@JvmInline
value class ToolId(val value: String)

@Serializable
@JvmInline
value class CapabilityId(val value: String)

/** The folder a chat's tools work in: files the agent writes and where commands start. */
@Serializable
@JvmInline
value class WorkspaceId(val value: String)

/** Ordered from least to most risky; the policy engine compares tiers by this order. */
@Serializable
enum class RiskTier {
    READ,

    /**
     * Changes only what's inside Whittle: the workspace every chat shares, and the Linux it runs in. Nothing else on
     * the phone is touched, but every project is in reach, so pre-approve it with care where nobody is watching.
     */
    WORKSPACE,

    /**
     * Reads public web content: a search, or an https page. Only a query or an address leaves the phone,
     * so it runs without asking, except where that address could carry personal data (see the policy engine).
     */
    WEB_READ,
    WRITE_LOCAL,
    NETWORK_OUT,
    SEND_OR_SHARE,
    DELETE_OR_PAY,
    ;

    /** Tools at these tiers can move data off the phone, so they are gated once a run is tainted. */
    val isOutbound: Boolean
        get() = this >= NETWORK_OUT
}

@Serializable
enum class ExecutionSite { DEVICE, SANDBOX, CONNECTOR, USER_CLOUD, PROVIDER }

data class ToolDefinition(
    val id: ToolId,
    val description: String,
    val inputSchema: JsonObject,
    val riskTier: RiskTier,
    val executionSite: ExecutionSite,
    val requiredCapabilities: Set<CapabilityId>,
    /** String-resource key for the plain-language consent text. Never generated by the model. */
    val consentTextKey: String,
    /** Whether this tool's output comes from outside the phone and must be treated as untrusted. */
    val outputProvenance: Provenance,
    /** Whether the output holds the user's personal data (contacts, calendar, ...). */
    val exposesPersonalData: Boolean = false,
    /** For a tool that comes from somewhere else (a connected server): how that source presents it. */
    val origin: ToolOrigin? = null,
)

/**
 * How a tool from elsewhere is shown: [title] is its provider's own name for it, [source] the service it
 * belongs to, and [site] that service's web host, whose icon stands in for the tool's.
 */
data class ToolOrigin(val title: String, val source: String, val site: String? = null)
